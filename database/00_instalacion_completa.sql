-- Normalizacion y auditoria compatibles con los LocalDateTime actuales de Java.
CREATE FUNCTION normalizar_persona() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    NEW.email := nullif(lower(btrim(NEW.email)), '');
    NEW.updated_at := localtimestamp;
    RETURN NEW;
END $$;
CREATE TRIGGER usuarios_normalizar BEFORE INSERT OR UPDATE ON usuarios FOR EACH ROW EXECUTE FUNCTION normalizar_persona();
CREATE TRIGGER clientes_normalizar BEFORE INSERT OR UPDATE ON clientes FOR EACH ROW EXECUTE FUNCTION normalizar_persona();

CREATE FUNCTION pedido_preparar() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'UPDATE' AND OLD.estado IN ('ENTREGADO','CANCELADO') THEN
        RAISE EXCEPTION 'Un pedido finalizado no se modifica';
    END IF;
    NEW.subtotal := round(NEW.total / (1 + NEW.tasa_igv), 2);
    NEW.igv := NEW.total - NEW.subtotal;
    NEW.updated_at := localtimestamp;
    IF TG_OP = 'INSERT' THEN
        IF NEW.mesa_id IS NOT NULL THEN SELECT numero INTO NEW.mesa_numero FROM mesas WHERE id = NEW.mesa_id; END IF;
        IF NEW.usuario_id IS NOT NULL THEN SELECT nombre || ' ' || apellido INTO NEW.mozo_nombre FROM usuarios WHERE id = NEW.usuario_id; END IF;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER pedido_preparar BEFORE INSERT OR UPDATE ON pedidos FOR EACH ROW EXECUTE FUNCTION pedido_preparar();

CREATE FUNCTION pedido_registrar_evento() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO pedido_eventos(pedido_id, estado_nuevo) VALUES (NEW.id, NEW.estado);
    ELSIF NEW.estado IS DISTINCT FROM OLD.estado THEN
        INSERT INTO pedido_eventos(pedido_id, estado_anterior, estado_nuevo) VALUES (NEW.id, OLD.estado, NEW.estado);
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER pedido_evento AFTER INSERT OR UPDATE ON pedidos FOR EACH ROW EXECUTE FUNCTION pedido_registrar_evento();

CREATE FUNCTION detalle_proteger() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE pid bigint; estado_pedido varchar(20);
BEGIN
    IF TG_OP = 'DELETE' THEN pid := OLD.pedido_id; ELSE pid := NEW.pedido_id; END IF;
    IF TG_OP = 'UPDATE' AND NEW.pedido_id <> OLD.pedido_id THEN RAISE EXCEPTION 'No se traslada un detalle a otro pedido'; END IF;
    SELECT estado INTO estado_pedido FROM pedidos WHERE id = pid FOR UPDATE;
    IF estado_pedido IN ('ENTREGADO','CANCELADO') THEN RAISE EXCEPTION 'El detalle pertenece a un pedido finalizado'; END IF;
    IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
    IF TG_OP = 'INSERT' THEN SELECT nombre INTO NEW.plato_nombre FROM platos WHERE id = NEW.plato_id; END IF;
    NEW.updated_at := localtimestamp;
    RETURN NEW;
END $$;
CREATE TRIGGER detalle_proteger BEFORE INSERT OR UPDATE OR DELETE ON pedido_detalles FOR EACH ROW EXECUTE FUNCTION detalle_proteger();

CREATE FUNCTION pago_validar() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE p pedidos%ROWTYPE; suma numeric;
BEGIN
    SELECT * INTO p FROM pedidos WHERE id = NEW.pedido_id FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Pedido inexistente'; END IF;
    IF p.estado <> 'TERMINADO' THEN RAISE EXCEPTION 'El pedido no esta listo para cobrar'; END IF;
    SELECT coalesce(sum(subtotal),0) INTO suma FROM pedido_detalles WHERE pedido_id = p.id;
    IF NEW.monto <> p.total OR p.total <> suma + p.costo_envio - p.descuento THEN
        RAISE EXCEPTION 'El pago no coincide con el detalle y total del pedido';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER pago_validar BEFORE INSERT ON pagos FOR EACH ROW EXECUTE FUNCTION pago_validar();

CREATE FUNCTION pago_inmutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'No se edita ni elimina un pago confirmado; implementar reversos auditables'; END $$;
CREATE TRIGGER pago_inmutable BEFORE UPDATE OR DELETE ON pagos FOR EACH ROW EXECUTE FUNCTION pago_inmutable();

CREATE FUNCTION resena_validar() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pedidos p JOIN pagos pa ON pa.pedido_id = p.id
                   WHERE p.id = NEW.pedido_id AND p.cliente_id = NEW.cliente_id) THEN
        RAISE EXCEPTION 'Solo el cliente del pedido pagado puede resenarlo';
    END IF;
    IF NEW.plato_id IS NOT NULL AND NOT EXISTS (SELECT 1 FROM pedido_detalles WHERE pedido_id = NEW.pedido_id AND plato_id = NEW.plato_id) THEN
        RAISE EXCEPTION 'El plato no pertenece a ese pedido';
    END IF;
    NEW.updated_at := now();
    RETURN NEW;
END $$;
CREATE TRIGGER resena_validar BEFORE INSERT OR UPDATE ON resenas FOR EACH ROW EXECUTE FUNCTION resena_validar();

