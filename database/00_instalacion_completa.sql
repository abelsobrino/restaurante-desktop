BEGIN;

CREATE TABLE IF NOT EXISTS public.proveedores (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ruc varchar(11) UNIQUE,
    nombre varchar(150) NOT NULL CHECK (btrim(nombre) <> ''),
    telefono varchar(30),
    email varchar(254),
    direccion text,
    activo boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (ruc IS NULL OR ruc ~ '^[0-9]{11}$')
);

CREATE TABLE IF NOT EXISTS public.ingredientes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(150) NOT NULL UNIQUE CHECK (btrim(nombre) <> ''),
    categoria varchar(80),
    unidad_base varchar(20) NOT NULL CHECK (unidad_base IN ('UNIDAD','GRAMO','MILILITRO')),
    stock_actual numeric(14,3) NOT NULL DEFAULT 0 CHECK (stock_actual >= 0),
    stock_minimo numeric(14,3) NOT NULL DEFAULT 0 CHECK (stock_minimo >= 0),
    costo_promedio numeric(14,6) NOT NULL DEFAULT 0 CHECK (costo_promedio >= 0),
    activo boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.proveedor_ingredientes (
    proveedor_id bigint NOT NULL REFERENCES public.proveedores(id) ON DELETE CASCADE,
    ingrediente_id bigint NOT NULL REFERENCES public.ingredientes(id) ON DELETE CASCADE,
    precio_referencia numeric(12,2) NOT NULL CHECK (precio_referencia >= 0),
    cantidad_referencia numeric(14,3) NOT NULL DEFAULT 1 CHECK (cantidad_referencia > 0),
    unidad_compra varchar(30),
    updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (proveedor_id, ingrediente_id)
);

CREATE TABLE IF NOT EXISTS public.compras (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proveedor_id bigint NOT NULL REFERENCES public.proveedores(id),
    usuario_id bigint REFERENCES public.usuarios(id),
    numero_documento varchar(60),
    fecha timestamptz NOT NULL DEFAULT now(),
    subtotal numeric(12,2) NOT NULL DEFAULT 0 CHECK (subtotal >= 0),
    igv numeric(12,2) NOT NULL DEFAULT 0 CHECK (igv >= 0),
    total numeric(12,2) NOT NULL DEFAULT 0 CHECK (total >= 0),
    observacion text,
    estado varchar(20) NOT NULL DEFAULT 'REGISTRADA' CHECK (estado IN ('REGISTRADA','ANULADA')),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.compra_detalles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compra_id bigint NOT NULL REFERENCES public.compras(id) ON DELETE CASCADE,
    ingrediente_id bigint NOT NULL REFERENCES public.ingredientes(id),
    cantidad_base numeric(14,3) NOT NULL CHECK (cantidad_base > 0),
    costo_total numeric(12,2) NOT NULL CHECK (costo_total >= 0),
    costo_unitario_base numeric(14,6) NOT NULL CHECK (costo_unitario_base >= 0),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.plato_ingredientes (
    plato_id bigint NOT NULL REFERENCES public.platos(id) ON DELETE CASCADE,
    ingrediente_id bigint NOT NULL REFERENCES public.ingredientes(id) ON DELETE RESTRICT,
    cantidad_base numeric(14,3) NOT NULL CHECK (cantidad_base > 0),
    PRIMARY KEY (plato_id, ingrediente_id)
);

CREATE TABLE IF NOT EXISTS public.plato_stock_diario (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plato_id bigint NOT NULL REFERENCES public.platos(id) ON DELETE CASCADE,
    fecha date NOT NULL,
    stock_inicial integer NOT NULL CHECK (stock_inicial >= 0),
    stock_actual integer NOT NULL CHECK (stock_actual >= 0),
    activo boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (plato_id, fecha)
);


-- -------------------------------------------------------------
-- Familias de platos / presentaciones.
-- Ej.: "Makis acevichados" -> x6, x12, x24.
-- Cada variante sigue siendo un registro normal de public.platos,
-- por lo que pedido_detalles, cocina, caja y reportes NO cambian.
-- -------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.plato_familias (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(150) NOT NULL CHECK (btrim(nombre) <> ''),
    descripcion varchar(255),
    categoria_id bigint NOT NULL REFERENCES public.categorias(id) ON DELETE RESTRICT,
    activo boolean NOT NULL DEFAULT true,
    orden integer NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_plato_familias_categoria_nombre
ON public.plato_familias(categoria_id, lower(nombre));

CREATE TABLE IF NOT EXISTS public.plato_familia_variantes (
    familia_id bigint NOT NULL REFERENCES public.plato_familias(id) ON DELETE CASCADE,
    plato_id bigint NOT NULL UNIQUE REFERENCES public.platos(id) ON DELETE CASCADE,
    etiqueta varchar(80) NOT NULL CHECK (btrim(etiqueta) <> ''),
    orden integer NOT NULL DEFAULT 0,
    activo boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (familia_id, plato_id)
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_plato_familia_etiqueta
ON public.plato_familia_variantes(familia_id, lower(etiqueta));

CREATE INDEX IF NOT EXISTS ix_plato_familias_categoria
ON public.plato_familias(categoria_id, activo, orden);

CREATE INDEX IF NOT EXISTS ix_plato_familia_variantes_familia
ON public.plato_familia_variantes(familia_id, activo, orden);

CREATE OR REPLACE VIEW public.vw_platos_opciones AS
SELECT
    f.id AS familia_id,
    f.nombre AS familia_nombre,
    f.descripcion AS familia_descripcion,
    f.categoria_id,
    f.activo AS familia_activa,
    fv.plato_id,
    fv.etiqueta,
    fv.orden AS variante_orden,
    fv.activo AS variante_activa,
    p.nombre AS plato_nombre,
    p.descripcion AS plato_descripcion,
    p.precio,
    p.tiempo_preparacion,
    p.disponible
FROM public.plato_familias f
JOIN public.plato_familia_variantes fv ON fv.familia_id = f.id
JOIN public.platos p ON p.id = fv.plato_id;

