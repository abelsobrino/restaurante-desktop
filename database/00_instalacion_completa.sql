CREATE TABLE categorias (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(50) NOT NULL UNIQUE CHECK (btrim(nombre) <> ''),
    descripcion varchar(255), activo boolean NOT NULL DEFAULT true,
    orden integer NOT NULL DEFAULT 0,
    created_at timestamp NOT NULL DEFAULT localtimestamp
);
CREATE UNIQUE INDEX uq_categoria_nombre_ci ON categorias (lower(btrim(nombre)));

CREATE TABLE usuarios (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dni varchar(8) NOT NULL UNIQUE CHECK (dni ~ '^[0-9]{8}$'),
    nombre varchar(255) NOT NULL CHECK (length(btrim(nombre)) BETWEEN 1 AND 100),
    apellido varchar(255) NOT NULL CHECK (length(btrim(apellido)) BETWEEN 1 AND 100),
    email varchar(255),
    password varchar(255), -- Solo hash BCrypt; NULL para MOZO.
    rol varchar(255) NOT NULL CHECK (rol IN ('MOZO','CAJERO','ADMIN','COCINERO')),
    activo boolean NOT NULL DEFAULT true,
    created_at timestamp NOT NULL DEFAULT localtimestamp,
    updated_at timestamp NOT NULL DEFAULT localtimestamp,
    CONSTRAINT ck_usuario_email CHECK (email IS NULL OR (length(email) <= 254 AND email ~ '^[^[:space:]@]+@[^[:space:]@]+[.][^[:space:]@]+$')),
    CONSTRAINT ck_usuario_clave_rol CHECK (
        (rol = 'MOZO' AND password IS NULL) OR
        (rol <> 'MOZO' AND password IS NOT NULL AND password ~ '^\$2[aby]\$[0-9]{2}\$[./A-Za-z0-9]{53}$')
    )
);
CREATE UNIQUE INDEX uq_usuario_email_ci ON usuarios (lower(btrim(email))) WHERE email IS NOT NULL;

CREATE TABLE mesas (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero integer NOT NULL UNIQUE CHECK (numero > 0),
    capacidad integer NOT NULL DEFAULT 4 CHECK (capacidad BETWEEN 1 AND 100),
    estado varchar(255) NOT NULL DEFAULT 'DISPONIBLE' CHECK (estado IN ('DISPONIBLE','OCUPADA','RESERVADA')),
    created_at timestamp NOT NULL DEFAULT localtimestamp
);

CREATE TABLE clientes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(255) NOT NULL CHECK (btrim(nombre) <> ''),
    apellido varchar(255) NOT NULL CHECK (btrim(apellido) <> ''),
    email varchar(255) NOT NULL CHECK (length(email) <= 254 AND email ~ '^[^[:space:]@]+@[^[:space:]@]+[.][^[:space:]@]+$'),
    password varchar(255), -- Hash local, nunca la clave de Gmail. NULL con OAuth.
    telefono varchar(255), direccion_default varchar(255),
    activo boolean NOT NULL DEFAULT true,
    email_verificado_at timestamptz,
    created_at timestamp NOT NULL DEFAULT localtimestamp,
    updated_at timestamp NOT NULL DEFAULT localtimestamp,
    CONSTRAINT ck_cliente_hash CHECK (password IS NULL OR password ~ '^\$2[aby]\$[0-9]{2}\$[./A-Za-z0-9]{53}$')
);
CREATE UNIQUE INDEX uq_cliente_email_ci ON clientes (lower(btrim(email)));

CREATE TABLE clientes_identidades (
