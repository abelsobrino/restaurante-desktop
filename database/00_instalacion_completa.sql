CREATE TABLE pedidos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo varchar(20) NOT NULL UNIQUE,
    tipo varchar(20) NOT NULL DEFAULT 'LOCAL' CHECK (tipo IN ('LOCAL','DELIVERY','RECOJO')),
    origen varchar(20) NOT NULL DEFAULT 'PRESENCIAL' CHECK (origen IN ('PRESENCIAL','WEB')),
    mesa_id bigint REFERENCES mesas(id) ON DELETE RESTRICT,
    usuario_id bigint REFERENCES usuarios(id) ON DELETE RESTRICT,
    cliente_id bigint REFERENCES clientes(id) ON DELETE RESTRICT,
    cliente_nombre varchar(255), cliente_telefono varchar(20), direccion_entrega varchar(255),
    estado varchar(20) NOT NULL DEFAULT 'PENDIENTE' CHECK (estado IN ('PENDIENTE','EN_PROCESO','LISTO','TERMINADO','ENTREGADO','CANCELADO')),
    subtotal numeric(38,2) NOT NULL DEFAULT 0 CHECK (subtotal >= 0), -- Base SIN IGV.
    total numeric(38,2) NOT NULL DEFAULT 0 CHECK (total >= 0), -- Total final CON IGV.
    igv numeric(38,2) NOT NULL DEFAULT 0 CHECK (igv >= 0),
    tasa_igv numeric(5,4) NOT NULL DEFAULT 0.18 CHECK (tasa_igv BETWEEN 0 AND 1),
    costo_envio numeric(10,2) NOT NULL DEFAULT 0 CHECK (costo_envio >= 0),
    descuento numeric(10,2) NOT NULL DEFAULT 0 CHECK (descuento >= 0),
    observacion_extra varchar(255), cerrado boolean NOT NULL DEFAULT false,
    mesa_numero integer, mozo_nombre varchar(255), -- Instantaneas de identificacion.
    clave_idempotencia uuid UNIQUE, -- El futuro backend debe enviar una clave estable por intento de pedido web.
    created_at timestamp NOT NULL DEFAULT localtimestamp,
    updated_at timestamp NOT NULL DEFAULT localtimestamp,
    fecha_cierre timestamp,
    CONSTRAINT ck_pedido_local CHECK (tipo <> 'LOCAL' OR mesa_id IS NOT NULL),
    CONSTRAINT ck_pedido_web CHECK (origen <> 'WEB' OR (cliente_id IS NOT NULL AND clave_idempotencia IS NOT NULL AND tipo IN ('DELIVERY','RECOJO'))),
    CONSTRAINT ck_delivery_direccion CHECK (tipo <> 'DELIVERY' OR (direccion_entrega IS NOT NULL AND btrim(direccion_entrega) <> ''))
);
