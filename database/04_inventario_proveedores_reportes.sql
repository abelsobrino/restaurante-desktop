-- Cancelar cabecera cancela sus detalles y activa la reposición anterior.
CREATE OR REPLACE FUNCTION public.fn_pedido_cancelado_propagar_detalles()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    IF OLD.estado <> 'CANCELADO' AND NEW.estado = 'CANCELADO' THEN
        UPDATE pedido_detalles
           SET estado = 'CANCELADO', updated_at = LOCALTIMESTAMP
         WHERE pedido_id = NEW.id
           AND estado <> 'CANCELADO';
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_pedido_cancelado_propagar_detalles ON public.pedidos;
-- IMPORTANTE: BEFORE, no AFTER. La BD original protege los detalles de pedidos
-- ya CANCELADOS; propagarlos antes del cambio de cabecera permite que el trigger
-- detalle_proteger los acepte y que después se reponga el stock correctamente.
CREATE TRIGGER trg_pedido_cancelado_propagar_detalles
BEFORE UPDATE OF estado ON public.pedidos
FOR EACH ROW EXECUTE FUNCTION public.fn_pedido_cancelado_propagar_detalles();

-- Función segura para ajuste manual desde el escritorio.
CREATE OR REPLACE FUNCTION public.ajustar_stock_ingrediente(
    p_ingrediente_id bigint,
    p_delta numeric,
    p_motivo text
) RETURNS numeric
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
    v_anterior numeric(14,3);
    v_nuevo numeric(14,3);
    v_tipo varchar(30);
BEGIN
    IF p_delta = 0 THEN
        RAISE EXCEPTION 'El ajuste no puede ser cero';
    END IF;

    SELECT stock_actual INTO v_anterior
      FROM ingredientes
     WHERE id = p_ingrediente_id
     FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Ingrediente no existe';
    END IF;

    v_nuevo := v_anterior + p_delta;
    IF v_nuevo < 0 THEN
        RAISE EXCEPTION 'El ajuste dejaría stock negativo. Stock actual: %', v_anterior;
    END IF;

    v_tipo := CASE WHEN p_delta > 0 THEN 'AJUSTE_ENTRADA' ELSE 'AJUSTE_SALIDA' END;

    UPDATE ingredientes
       SET stock_actual = v_nuevo, updated_at = now()
     WHERE id = p_ingrediente_id;

    INSERT INTO inventario_movimientos(
        ingrediente_id, tipo, cantidad, stock_anterior, stock_nuevo, motivo
    ) VALUES (
        p_ingrediente_id, v_tipo, abs(p_delta), v_anterior, v_nuevo, p_motivo
    );

    RETURN v_nuevo;
END;
$$;

