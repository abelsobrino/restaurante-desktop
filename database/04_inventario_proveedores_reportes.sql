    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(150) NOT NULL UNIQUE CHECK (btrim(nombre) <> ''),
    categoria varchar(80),
    unidad_base varchar(20) NOT NULL CHECK (unidad_base IN ('UNIDAD','GRAMO','MILILITRO')),
    stock_actual numeric(14,3) NOT NULL DEFAULT 0 CHECK (stock_actual >= 0),
    stock_minimo numeric(14,3) NOT NULL DEFAULT 0 CHECK (stock_minimo >= 0),
    costo_promedio numeric(14,6) NOT NULL DEFAULT 0 CHECK (costo_promedio >= 0),
    activo boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

