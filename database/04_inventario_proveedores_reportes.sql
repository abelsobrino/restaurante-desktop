DO $$
DECLARE t text; r text;
BEGIN
    FOREACH t IN ARRAY ARRAY[
        'proveedores','ingredientes','proveedor_ingredientes','compras','compra_detalles',
        'plato_ingredientes','plato_stock_diario','plato_familias','plato_familia_variantes',
        'inventario_movimientos','plato_stock_movimientos','mermas','gastos','caja_cierres'
    ] LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format('REVOKE ALL ON TABLE public.%I FROM PUBLIC', t);
        FOREACH r IN ARRAY ARRAY['anon','authenticated'] LOOP
            IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = r) THEN
                EXECUTE format('REVOKE ALL ON TABLE public.%I FROM %I', t, r);
            END IF;
        END LOOP;
    END LOOP;
END $$;

