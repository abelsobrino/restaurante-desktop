-- -------------------------------------------------------------
-- Vista: stock vendible HOY.
-- Regla operativa: cada día empieza en 0. Si no existe fila de stock
-- para hoy, el plato NO se puede vender. La receta se consume al
-- habilitar/preparar stock, no nuevamente al vender.
-- -------------------------------------------------------------
CREATE OR REPLACE VIEW public.vw_platos_stock_hoy AS
SELECT p.id AS plato_id,
       COALESCE(d.stock_actual, 0)::integer AS stock_diario,
       COALESCE(d.stock_actual, 0)::integer AS stock_disponible
FROM public.platos p
LEFT JOIN public.plato_stock_diario d
  ON d.plato_id = p.id
 AND d.fecha = (now() AT TIME ZONE 'America/Lima')::date
 AND d.activo;

-- Configurar el stock diario equivale a habilitar/preparar porciones.
-- Al AUMENTAR porciones se descuentan los ingredientes de receta.
-- Al REDUCIR porciones no vendidas se devuelven al almacén.
-- Insumos generales no incluidos en la receta (ej. aceite de freidora)
-- se controlan con ajuste manual.
CREATE OR REPLACE FUNCTION public.configurar_stock_diario(
    p_plato_id bigint, p_fecha date, p_stock_inicial integer
) RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_hoy date := (now() AT TIME ZONE 'America/Lima')::date;
    v_anterior_inicial integer := 0;
    v_anterior_actual integer := 0;
    v_vendido integer := 0;
    v_delta integer := 0;
    v_nuevo_actual integer := 0;
    v_reservado boolean := false;
    v_rec record;
    v_stock numeric(14,3);
    v_requerido numeric(14,3);
BEGIN
    IF p_fecha IS NULL THEN p_fecha := v_hoy; END IF;
    IF p_fecha <> v_hoy THEN
        RAISE EXCEPTION 'El stock operativo solo se configura para hoy (%)', v_hoy;
    END IF;
    IF p_stock_inicial IS NULL OR p_stock_inicial < 0 THEN
        RAISE EXCEPTION 'El stock inicial debe ser 0 o mayor';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM platos WHERE id = p_plato_id AND disponible) THEN
        RAISE EXCEPTION 'El plato no existe o está deshabilitado';
    END IF;

    SELECT stock_inicial, stock_actual, inventario_reservado
      INTO v_anterior_inicial, v_anterior_actual, v_reservado
      FROM plato_stock_diario
     WHERE plato_id = p_plato_id AND fecha = p_fecha
     FOR UPDATE;
    IF NOT FOUND THEN
        v_anterior_inicial := 0; v_anterior_actual := 0; v_reservado := true;
    END IF;

    v_vendido := GREATEST(v_anterior_inicial - v_anterior_actual, 0);
    IF p_stock_inicial < v_vendido THEN
        RAISE EXCEPTION 'No puedes bajar el stock inicial por debajo de lo ya vendido (% porciones)', v_vendido;
    END IF;
    v_nuevo_actual := p_stock_inicial - v_vendido;
    -- Filas creadas por la versión anterior no tenían reserva de receta.
    -- En su primera edición reservamos solo las porciones que siguen sin vender.
    v_delta := CASE WHEN v_reservado THEN p_stock_inicial - v_anterior_inicial ELSE v_nuevo_actual END;

    -- Bloqueo en orden estable para evitar carreras entre administradores.
    FOR v_rec IN
        SELECT pi.ingrediente_id, pi.cantidad_base, i.nombre, i.activo
          FROM plato_ingredientes pi
          JOIN ingredientes i ON i.id = pi.ingrediente_id
         WHERE pi.plato_id = p_plato_id
         ORDER BY pi.ingrediente_id
    LOOP
        IF NOT v_rec.activo THEN
            RAISE EXCEPTION 'Ingrediente % está inactivo', v_rec.nombre;
        END IF;
        SELECT stock_actual INTO v_stock FROM ingredientes WHERE id=v_rec.ingrediente_id FOR UPDATE;
        v_requerido := v_rec.cantidad_base * abs(v_delta);
        IF v_delta > 0 THEN
            IF v_stock < v_requerido THEN
                RAISE EXCEPTION 'No alcanza %: disponible %, requerido % para habilitar % porciones adicionales',
                    v_rec.nombre, v_stock, v_requerido, v_delta;
            END IF;
            UPDATE ingredientes SET stock_actual=stock_actual-v_requerido, updated_at=now() WHERE id=v_rec.ingrediente_id;
            INSERT INTO inventario_movimientos(ingrediente_id,tipo,cantidad,stock_anterior,stock_nuevo,motivo)
            VALUES(v_rec.ingrediente_id,'AJUSTE_SALIDA',v_requerido,v_stock,v_stock-v_requerido,
                   'Producción diaria / habilitación de stock del plato '||p_plato_id);
        ELSIF v_delta < 0 THEN
            UPDATE ingredientes SET stock_actual=stock_actual+v_requerido, updated_at=now() WHERE id=v_rec.ingrediente_id;
            INSERT INTO inventario_movimientos(ingrediente_id,tipo,cantidad,stock_anterior,stock_nuevo,motivo)
            VALUES(v_rec.ingrediente_id,'AJUSTE_ENTRADA',v_requerido,v_stock,v_stock+v_requerido,
                   'Reducción de producción diaria del plato '||p_plato_id);
        END IF;
    END LOOP;

    INSERT INTO plato_stock_diario(plato_id,fecha,stock_inicial,stock_actual,activo,inventario_reservado,updated_at)
    VALUES(p_plato_id,p_fecha,p_stock_inicial,v_nuevo_actual,true,true,now())
    ON CONFLICT(plato_id,fecha) DO UPDATE SET
        stock_inicial=excluded.stock_inicial, stock_actual=excluded.stock_actual, activo=true, inventario_reservado=true, updated_at=now();
    RETURN v_nuevo_actual;
END;
$$;

-- -------------------------------------------------------------
-- Compra: cada detalle aumenta inventario y recalcula costo medio.
-- -------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_compra_detalle_ingresa_stock()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_anterior numeric(14,3);
    v_nuevo numeric(14,3);
    v_costo_anterior numeric(14,6);
    v_costo_nuevo numeric(14,6);
    v_proveedor bigint;
BEGIN
    SELECT stock_actual, costo_promedio
      INTO v_anterior, v_costo_anterior
      FROM ingredientes
     WHERE id = NEW.ingrediente_id
     FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Ingrediente % no existe', NEW.ingrediente_id;
    END IF;

    v_nuevo := v_anterior + NEW.cantidad_base;
    IF v_nuevo > 0 THEN
        v_costo_nuevo := ((v_anterior * v_costo_anterior) + NEW.costo_total) / v_nuevo;
    ELSE
        v_costo_nuevo := NEW.costo_unitario_base;
    END IF;

    UPDATE ingredientes
       SET stock_actual = v_nuevo,
           costo_promedio = ROUND(v_costo_nuevo, 6),
           updated_at = now()
     WHERE id = NEW.ingrediente_id;

    INSERT INTO inventario_movimientos(
        ingrediente_id, tipo, cantidad, stock_anterior, stock_nuevo,
        compra_detalle_id, motivo
    ) VALUES (
        NEW.ingrediente_id, 'ENTRADA_COMPRA', NEW.cantidad_base,
        v_anterior, v_nuevo, NEW.id, 'Compra registrada'
    );

    SELECT proveedor_id INTO v_proveedor FROM compras WHERE id = NEW.compra_id;
    INSERT INTO proveedor_ingredientes(
        proveedor_id, ingrediente_id, precio_referencia, cantidad_referencia, unidad_compra, updated_at
    ) VALUES (
        v_proveedor, NEW.ingrediente_id, NEW.costo_total, COALESCE(NEW.cantidad_compra, NEW.cantidad_base),
        COALESCE(NEW.unidad_compra, (SELECT unidad_base FROM ingredientes WHERE id = NEW.ingrediente_id)), now()
    )
    ON CONFLICT (proveedor_id, ingrediente_id) DO UPDATE SET
        precio_referencia = EXCLUDED.precio_referencia,
        cantidad_referencia = EXCLUDED.cantidad_referencia,
        unidad_compra = EXCLUDED.unidad_compra,
        updated_at = now();

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_compra_detalle_ingresa_stock ON public.compra_detalles;
CREATE TRIGGER trg_compra_detalle_ingresa_stock
AFTER INSERT ON public.compra_detalles
FOR EACH ROW EXECUTE FUNCTION public.fn_compra_detalle_ingresa_stock();

-- -------------------------------------------------------------
-- Venta: descuenta SOLO las porciones del stock diario.
-- Los ingredientes ya fueron consumidos/reservados cuando el admin
-- habilitó esas porciones mediante configurar_stock_diario().
-- Sin stock configurado hoy => venta bloqueada (incluye web).
-- -------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_pedido_detalle_descontar_stock()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_stock_id bigint;
    v_stock_actual integer;
    v_fecha date := (now() AT TIME ZONE 'America/Lima')::date;
BEGIN
    IF NEW.estado = 'CANCELADO' THEN RETURN NEW; END IF;

    SELECT id, stock_actual INTO v_stock_id, v_stock_actual
      FROM plato_stock_diario
     WHERE plato_id=NEW.plato_id AND fecha=v_fecha AND activo
     FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'El plato % no tiene stock habilitado para hoy', NEW.plato_id;
    END IF;
    IF v_stock_actual < NEW.cantidad THEN
        RAISE EXCEPTION 'Stock diario insuficiente para el plato %. Disponible: %, solicitado: %',
            NEW.plato_id, v_stock_actual, NEW.cantidad;
    END IF;

    UPDATE plato_stock_diario SET stock_actual=stock_actual-NEW.cantidad, updated_at=now() WHERE id=v_stock_id;
    INSERT INTO plato_stock_movimientos(plato_stock_id,pedido_detalle_id,tipo,cantidad,stock_anterior,stock_nuevo)
    VALUES(v_stock_id,NEW.id,'SALIDA_VENTA',NEW.cantidad,v_stock_actual,v_stock_actual-NEW.cantidad);
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_pedido_detalle_descontar_stock ON public.pedido_detalles;
CREATE TRIGGER trg_pedido_detalle_descontar_stock
AFTER INSERT ON public.pedido_detalles
FOR EACH ROW EXECUTE FUNCTION public.fn_pedido_detalle_descontar_stock();

-- -------------------------------------------------------------
-- Cancelación de un detalle: repone exactamente lo descontado.
-- -------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_pedido_detalle_reponer_stock()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_mov record;
    v_anterior numeric(14,3);
    v_stock_mov record;
    v_stock_anterior integer;
BEGIN
    IF OLD.estado <> 'CANCELADO' AND NEW.estado = 'CANCELADO' THEN
        FOR v_mov IN
            SELECT * FROM inventario_movimientos
             WHERE pedido_detalle_id = NEW.id
               AND tipo = 'SALIDA_VENTA'
               AND NOT reversado
             ORDER BY id
             FOR UPDATE
        LOOP
            SELECT stock_actual INTO v_anterior
              FROM ingredientes
             WHERE id = v_mov.ingrediente_id
             FOR UPDATE;

            UPDATE ingredientes
               SET stock_actual = stock_actual + v_mov.cantidad,
                   updated_at = now()
             WHERE id = v_mov.ingrediente_id;

            INSERT INTO inventario_movimientos(
                ingrediente_id, tipo, cantidad, stock_anterior, stock_nuevo,
                pedido_detalle_id, motivo
            ) VALUES (
                v_mov.ingrediente_id, 'DEVOLUCION_CANCELACION', v_mov.cantidad,
                v_anterior, v_anterior + v_mov.cantidad, NEW.id,
                'Reposición por cancelación de pedido'
            );

            UPDATE inventario_movimientos SET reversado = true WHERE id = v_mov.id;
        END LOOP;

        FOR v_stock_mov IN
            SELECT * FROM plato_stock_movimientos
             WHERE pedido_detalle_id = NEW.id
               AND tipo = 'SALIDA_VENTA'
               AND NOT reversado
             ORDER BY id
             FOR UPDATE
        LOOP
            SELECT stock_actual INTO v_stock_anterior
              FROM plato_stock_diario
             WHERE id = v_stock_mov.plato_stock_id
             FOR UPDATE;

            UPDATE plato_stock_diario
               SET stock_actual = stock_actual + v_stock_mov.cantidad,
                   updated_at = now()
             WHERE id = v_stock_mov.plato_stock_id;

            INSERT INTO plato_stock_movimientos(
                plato_stock_id, pedido_detalle_id, tipo, cantidad,
                stock_anterior, stock_nuevo
            ) VALUES (
                v_stock_mov.plato_stock_id, NEW.id, 'DEVOLUCION_CANCELACION',
                v_stock_mov.cantidad, v_stock_anterior,
                v_stock_anterior + v_stock_mov.cantidad
            );

            UPDATE plato_stock_movimientos SET reversado = true WHERE id = v_stock_mov.id;
        END LOOP;
    END IF;

    RETURN NEW;
END;
$$;

